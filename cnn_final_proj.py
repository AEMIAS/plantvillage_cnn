from pathlib import Path
import random
import numpy as np
import matplotlib.pyplot as plt

import torch
from torch import nn

from torch.utils.data import DataLoader, Subset, random_split
from torchvision import datasets, transforms

import torch.optim as optim

SEED = 42

random.seed(SEED)
np.random.seed(SEED)
torch.manual_seed(SEED)

if torch.cuda.is_available():
    torch.cuda.manual_seed_all(SEED)

BATCH_SIZE = 64

FAST_MODE = False

EPOCHS = 2 if FAST_MODE else 15

LEARNING_RATE = 0.001

IMG_SIZE = 128

if torch.cuda.is_available():
    device = torch.device("cuda")
else:
    device = torch.device("cpu")

print("PyTorch:", torch.__version__)
print("Using device:", device)

from datasets import load_dataset

hf_data = load_dataset("BrandonFors/Plant-Diseases-PlantVillage-Dataset")
print(hf_data)


if "test" not in hf_data:
    hf_data = hf_data["train"].train_test_split(test_size=0.2, seed=SEED)


IMAGE_COL = "image"
LABEL_COL = "label"

print(hf_data["train"].features)

MEAN = (0.485, 0.456, 0.406)
STD = (0.229, 0.224, 0.225)

transform = transforms.Compose([
    transforms.Resize((IMG_SIZE, IMG_SIZE)),
    transforms.ToTensor(),
    transforms.Normalize(
        mean=MEAN,
        std=STD
    )
])

all_classes = hf_data["train"].features[LABEL_COL].names

crops = sorted({c.split("___")[0] for c in all_classes})
print("Available crops:", crops)

CROP = "Tomato"
assert CROP in crops, f"{CROP} not found, choose from: {crops}"

selected_ids = [i for i, c in enumerate(all_classes) if c.startswith(CROP + "___")]

# old label id -> new id (0..N-1)
label_map = {old: new for new, old in enumerate(selected_ids)}

class_names = [all_classes[i] for i in selected_ids]
NUM_CLASSES = len(class_names)


train_hf = hf_data["train"].filter(lambda l: l in label_map, input_columns=LABEL_COL)
test_hf = hf_data["test"].filter(lambda l: l in label_map, input_columns=LABEL_COL)


class HFImageDataset(torch.utils.data.Dataset):
    """Wraps a Hugging Face dataset so it works with PyTorch DataLoader."""

    def __init__(self, hf_ds, transform, label_map):
        self.ds = hf_ds
        self.transform = transform
        self.label_map = label_map

    def __len__(self):
        return len(self.ds)

    def __getitem__(self, idx):
        item = self.ds[idx]
        image = item[IMAGE_COL].convert("RGB")
        return self.transform(image), self.label_map[item[LABEL_COL]]


full_train = HFImageDataset(train_hf, transform, label_map)
cifar_like_test = HFImageDataset(test_hf, transform, label_map)

print("Crop:", CROP)
print("Train+Val images:", len(full_train))
print("Test images:", len(cifar_like_test))
print("Number of classes:", NUM_CLASSES)
print("Classes:", class_names)

# The dataset already has train/test splits (80/20), so we only carve a validation set out of train
split_generator = torch.Generator().manual_seed(SEED)

val_size = int(0.15 * len(full_train))
train_size = len(full_train) - val_size

train_full, val_full = random_split(
    full_train, [train_size, val_size], generator=split_generator)

test_full = cifar_like_test



if FAST_MODE:
    train_data = Subset(train_full, range(min(5_000, len(train_full))))

    val_data = Subset(val_full, range(min(1_000, len(val_full))))

    test_data = Subset(test_full, range(min(2_000, len(test_full))))

else:
    train_data = train_full
    val_data = val_full
    test_data = test_full

print("Train:", len(train_data))
print("Validation:", len(val_data))
print("Test:", len(test_data))

loader_generator = torch.Generator().manual_seed(SEED)

train_loader = DataLoader(train_data, batch_size=BATCH_SIZE, shuffle=True,
                          num_workers=0, generator=loader_generator)

val_loader = DataLoader(val_data, batch_size=BATCH_SIZE, num_workers=0)

test_loader = DataLoader(test_data, batch_size=BATCH_SIZE, shuffle=False, num_workers=0)

images, labels = next(iter(train_loader))

print("Image batch:", tuple(images.shape), images.dtype)
print("Label batch:", tuple(labels.shape), labels.dtype)

print("Pixel range:", float(images.min()), "to", float(images.max()))

print("First labels:", labels[:10].tolist())

class CNN(nn.Module):

    def __init__(self, num_classes):
        super().__init__()

        self.features = nn.Sequential(
            # Block 1
            nn.Conv2d(in_channels=3, out_channels=32, kernel_size=3, padding=1),

            nn.ReLU(),

            nn.MaxPool2d(kernel_size=2),

            # Block 2
            nn.Conv2d(in_channels=32, out_channels=64, kernel_size=3, padding=1),

            nn.ReLU(),

            nn.MaxPool2d(kernel_size=2),

            # Block 3
            nn.Conv2d(in_channels=64, out_channels=128, kernel_size=3, padding=1),

            nn.ReLU(),

            nn.MaxPool2d(kernel_size=2),
        )


        feat_size = IMG_SIZE // 8

        self.classifier = nn.Sequential(
            nn.Flatten(), nn.Linear(128 * feat_size * feat_size, 256), nn.ReLU(),
            nn.Dropout(0.3), nn.Linear(256, num_classes))

    def forward(self, x):

        x = self.features(x)

        x = self.classifier(x)

        return x

model = CNN(NUM_CLASSES).to(device)

criterion = nn.CrossEntropyLoss()

optimizer = optim.Adam(model.parameters(), lr=LEARNING_RATE)

print(model)
print("Device:", device)

history = {"train_loss": [], "val_loss": [], "train_acc": [], "val_acc": []}

for epoch in range(EPOCHS):


    model.train()

    running_loss = 0.0
    train_correct = 0
    train_total = 0

    for images, labels in train_loader:

        images = images.to(device)
        labels = labels.to(device)

        outputs = model(images)

        loss = criterion(outputs, labels)

        optimizer.zero_grad()

        loss.backward()

        optimizer.step()

        running_loss += loss.item()

        predictions = outputs.argmax(dim=1)
        train_total += labels.size(0)
        train_correct += (predictions == labels).sum().item()

    epoch_loss = running_loss / len(train_loader)
    train_accuracy = 100 * train_correct / train_total


    model.eval()

    val_running_loss = 0.0
    val_correct = 0
    val_total = 0

    with torch.no_grad():

        for images, labels in val_loader:

            images = images.to(device)
            labels = labels.to(device)

            outputs = model(images)

            loss = criterion(outputs, labels)
            val_running_loss += loss.item()

            predictions = outputs.argmax(dim=1)

            val_total += labels.size(0)

            val_correct += (predictions == labels).sum().item()

    val_loss = val_running_loss / len(val_loader)
    val_accuracy = 100 * val_correct / val_total


    history["train_loss"].append(epoch_loss)
    history["val_loss"].append(val_loss)
    history["train_acc"].append(train_accuracy)
    history["val_acc"].append(val_accuracy)

    print(
        f"Epoch [{epoch+1}/{EPOCHS}] "
        f"Train Loss: {epoch_loss:.4f} | Train Acc: {train_accuracy:.2f}% | "
        f"Val Loss: {val_loss:.4f} | Val Acc: {val_accuracy:.2f}%"
    )

epochs_range = range(1, len(history["train_acc"]) + 1)

plt.figure(figsize=(12, 4))


plt.subplot(1, 2, 1)
plt.plot(epochs_range, history["train_acc"], marker="o", label="Train Acc")
plt.plot(epochs_range, history["val_acc"], marker="o", label="Val Acc")
plt.title("Training vs Validation Accuracy")
plt.xlabel("Epoch")
plt.ylabel("Accuracy (%)")
plt.legend()
plt.grid(True)


plt.subplot(1, 2, 2)
plt.plot(epochs_range, history["train_loss"], marker="o", label="Train Loss")
plt.plot(epochs_range, history["val_loss"], marker="o", label="Val Loss")
plt.title("Training vs Validation Loss")
plt.xlabel("Epoch")
plt.ylabel("Loss")
plt.legend()
plt.grid(True)

plt.tight_layout()
plt.show()

# test
model.eval()

correct = 0
total = 0

with torch.no_grad():

    for images, labels in test_loader:

        images = images.to(device)
        labels = labels.to(device)

        outputs = model(images)

        predictions = outputs.argmax(dim=1)

        total += labels.size(0)

        correct += (predictions == labels).sum().item()

accuracy = 100 * correct / total

print(f"Test Accuracy: {accuracy:.2f}%")



